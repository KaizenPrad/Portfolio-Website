import fs from 'node:fs';
import path from 'node:path';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const families = [
  'Space+Grotesk:wght@300..700',
  'Inter:wght@300..600',
  'JetBrains+Mono:wght@400..600',
];

const OUT_DIR = 'public/fonts';
fs.mkdirSync(OUT_DIR, { recursive: true });

let css = '';
const seen = new Map();

for (const fam of families) {
  const url = `https://fonts.googleapis.com/css2?family=${fam}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  let text = await res.text();
  // keep only the latin subset blocks
  const blocks = text.split('/*').filter(Boolean);
  for (const block of blocks) {
    if (!block.includes('latin')) continue;
    const m = block.match(/src:\s*url\((https:[^)]+)\)/);
    if (!m) continue;
    const familyMatch = block.match(/font-family:\s*'([^']+)'/);
    const weightMatch = block.match(/font-weight:\s*([^;]+);/);
    const styleMatch = block.match(/font-style:\s*([^;]+);/);
    const unicodeMatch = block.match(/unicode-range:\s*([^;]+);/);
    const fileName = `${familyMatch[1].replace(/\s+/g, '')}-${(weightMatch?.[1] ?? '400').replace(/\s+/g, '-')}.woff2`;
    const localPath = path.join(OUT_DIR, fileName);
    if (!seen.has(fileName)) {
      const fontRes = await fetch(m[1], { headers: { 'User-Agent': UA } });
      const buf = Buffer.from(await fontRes.arrayBuffer());
      fs.writeFileSync(localPath, buf);
      seen.set(fileName, buf.length);
      console.log('saved', fileName, buf.length, 'bytes');
    }
    css += `@font-face {
  font-family: '${familyMatch[1]}';
  font-style: ${styleMatch?.[1] ?? 'normal'};
  font-weight: ${weightMatch?.[1] ?? '400'};
  font-display: swap;
  src: url('/fonts/${fileName}') format('woff2');
${unicodeMatch ? `  unicode-range: ${unicodeMatch[1]};` : ''}
}
`;
  }
}

fs.writeFileSync('src/styles/fonts.css', `/* Self-hosted fonts — generated by scripts/fetch-fonts.mjs */\n\n${css}`);
console.log('\nwrote src/styles/fonts.css');

