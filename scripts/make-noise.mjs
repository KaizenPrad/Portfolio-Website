import sharp from 'sharp';
import fs from 'node:fs';

// Generate a small static noise tile (much cheaper to rasterise than an SVG filter)
const W = 96;
const H = 96;
const data = Buffer.alloc(W * H * 4);
for (let i = 0; i < W * H; i++) {
  const v = 118 + Math.floor(Math.random() * 74);
  data[i * 4] = v;
  data[i * 4 + 1] = v;
  data[i * 4 + 2] = v;
  data[i * 4 + 3] = 255;
}
const png = await sharp(data, { raw: { width: W, height: H, channels: 4 } })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();
fs.writeFileSync('public/images/noise.png', png);
console.log('noise.png', png.length, 'bytes');

const b64 = png.toString('base64');
fs.writeFileSync(
  'src/styles/noise.css',
  `/* Generated by scripts/make-noise.mjs — static noise tile (no SVG filter cost) */\n\n.noise-tile {\n  background-image: url("data:image/png;base64,${b64}");\n  background-repeat: repeat;\n  background-size: ${W}px ${H}px;\n}\n`,
);
console.log('wrote src/styles/noise.css', b64.length, 'base64 chars');
